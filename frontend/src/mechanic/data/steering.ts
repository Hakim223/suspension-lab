export function findSteeringPart(id: string): { system: SteeringSystem; part: SteeringPart } | null {
  for (const system of STEERING_SYSTEMS) {
    const part = system.parts.find((p) => p.id === id);
    if (part) return { system, part };
  }
  return null;
}
